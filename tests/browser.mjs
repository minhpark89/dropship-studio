import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { startServer } from '../server/index.js';

const root = path.resolve('.verification', `ui-${randomUUID()}`);
const output = path.resolve('.verification/ui');
await fs.mkdir(output, { recursive: true });
const fixture = JSON.parse(await fs.readFile('.verification/render-result.json', 'utf8'));
const studio = await startServer({ port: 0, dataDir: root });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
page.on('dialog', (dialog) => dialog.accept());
const nav = async (name) => {
  await page.locator('nav').getByRole('button', { name, exact: true }).click();
  await page.locator('nav button.active').filter({ hasText: name }).waitFor();
};
const report = { checks: [], errors, root, url: studio.address };
try {
  await page.goto(studio.address);
  await page.getByRole('heading', { name: 'Bắt đầu bằng một ý tưởng.' }).waitFor();
  await page.screenshot({ path: path.join(output, 'create.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  report.checks.push('Initial screen: no horizontal overflow at 1440px');
  await page.getByRole('button', { name: 'Tạo dự án', exact: true }).click();
  await page.getByLabel('Tên dự án').fill('QA · tiếng Việt');
  await page.getByRole('dialog').getByRole('button', { name: 'Tạo dự án', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await nav('Thư viện');
  const sources = ['video có âm thanh.mp4', 'video im lặng.mp4', 'logo.png', 'nhạc.wav'];
  await page.locator('.upload-zone input').first().setInputFiles(sources.map((name) => path.join(fixture.root, name)));
  await page.getByRole('heading', { name: 'video có âm thanh.mp4', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'nhạc.wav', exact: true }).waitFor();
  for (const source of sources) await page.getByRole('checkbox', { name: `Chọn ${source}`, exact: true }).check();
  await page.getByRole('button', { name: 'Thêm vào timeline', exact: true }).click();
  await page.getByRole('heading', { name: 'Dựng câu chuyện của bạn.' }).waitFor();
  report.checks.push('Created project, uploaded four real files with Unicode names, added clips and music');
  await page.getByRole('button', { name: 'Tạm dừng xem trước' }).click();
  await page.getByRole('button', { name: 'Về đầu', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'editor-t0.png'), fullPage: true });
  const initial = await page.getByTestId('playback-time').innerText();
  await page.getByRole('button', { name: 'Phát xem trước' }).click();
  await page.waitForTimeout(1200);
  const later = await page.getByTestId('playback-time').innerText();
  assert.notEqual(initial, later);
  const videoTime = await page.locator('.preview-source').evaluate((element) => element.currentTime);
  assert.ok(videoTime > 0.5, `actual video time ${videoTime}`);
  await page.screenshot({ path: path.join(output, 'editor-t1.png'), fullPage: true });
  await page.getByRole('button', { name: 'Tạm dừng xem trước' }).click();
  await page.getByRole('button', { name: 'Cắt tại con trỏ' }).click();
  assert.equal(await page.locator('.timeline-clip').count(), 4);
  await page.getByRole('button', { name: 'Hoàn tác', exact: true }).click();
  assert.equal(await page.locator('.timeline-clip').count(), 3);
  await page.getByRole('button', { name: 'Làm lại', exact: true }).click();
  assert.equal(await page.locator('.timeline-clip').count(), 4);
  report.checks.push('requestAnimationFrame advances video; split and undo/redo work');
  await page.getByRole('button', { name: 'Thêm chữ', exact: true }).click();
  await page.getByLabel('Nội dung', { exact: true }).fill('Sản phẩm Việt · 100%');
  const overlay = page.locator('.preview-overlay.text');
  const box = await overlay.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 - 20, box.y + box.height / 2 - 45, { steps: 6 });
  await page.mouse.up();
  assert.ok(Number(await page.getByLabel('Vị trí Y (%)', { exact: true }).inputValue()) < 75);
  await page.getByRole('button', { name: 'Thêm logo', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'logo.png', exact: true }).click();
  await page.getByLabel('Tỷ lệ video').selectOption('16:9');
  const frame = await page.locator('.preview-frame').boundingBox();
  report.previewRatio = frame.width / frame.height;
  assert.ok(Math.abs(report.previewRatio - 16 / 9) < 0.01);
  await page.screenshot({ path: path.join(output, 'editor-landscape.png'), fullPage: true });
  await page.getByLabel('Tỷ lệ video').selectOption('9:16');
  await page.getByRole('button', { name: 'Xuất video', exact: true }).click();
  await page.getByLabel('Tên file', { exact: true }).fill('QA browser export');
  await page.getByLabel('Độ phân giải').selectOption('480');
  await page.getByRole('button', { name: 'Bắt đầu xuất', exact: true }).click();
  await page.getByRole('heading', { name: 'Ý tưởng đang thành hình.' }).waitFor();
  await page.locator('.job-card .badge.completed').first().waitFor({ timeout: 60000 });
  const result = studio.store.state.jobs.find((job) => job.name === 'QA browser export');
  assert.equal(result.status, 'completed', result.error);
  assert.ok(studio.store.state.media.find((item) => item.id === result.mediaId)?.duration > 9.9);
  report.checks.push('Text dragging, logo, aspect ratio, and export via UI completed with a real MP4');
  await nav('Kịch bản');
  await page.getByLabel('Sản phẩm', { exact: true }).fill('Giày thể thao');
  await page.getByLabel('Điểm nổi bật', { exact: true }).fill('nhẹ và thoáng');
  await page.getByRole('button', { name: 'Thêm 4 cảnh mẫu' }).click();
  assert.equal(await page.locator('.story-scene').count(), 4);
  await page.getByRole('button', { name: 'Chuyển sang tạo AI' }).click();
  await page.getByRole('heading', { name: 'Bắt đầu bằng một ý tưởng.' }).waitFor();
  assert.ok((await page.getByLabel('Bạn muốn tạo điều gì?').inputValue()).includes('Giày thể thao'));
  await page.getByRole('button', { name: 'Tạo 4 nội dung', exact: true }).click();
  await page.getByRole('heading', { name: 'Ý tưởng đang thành hình.' }).waitFor();
  assert.equal(studio.store.state.jobs.filter((job) => job.type === 'generate' && job.status === 'queued').length, 4);
  assert.equal(studio.store.state.jobs.filter((job) => job.submittedAt).length, 0);
  await page.getByRole('button', { name: /Hủy Video 1/ }).click();
  await page.waitForTimeout(300);
  assert.equal(studio.store.state.jobs.filter((job) => job.status === 'cancelled').length, 1);
  report.checks.push('Storyboard creates prompts; AI jobs wait for login without sending; cancellation works');
  await nav('Tài khoản');
  await page.getByRole('button', { name: 'Thêm tài khoản', exact: true }).click();
  await page.getByLabel('Cách đăng nhập').selectOption('cookie');
  await page.getByLabel('Tên dễ nhớ').fill('QA chưa đăng nhập');
  await page.getByRole('dialog').getByLabel('Cookie', { exact: true }).fill('not-a-cookie');
  await page.getByRole('dialog').getByRole('button', { name: 'Hủy', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(studio.store.state.accounts.length, 0);
  await page.screenshot({ path: path.join(output, 'accounts.png'), fullPage: true });
  await nav('Cài đặt');
  await page.getByText('Chrome / Edge', { exact: true }).waitFor();
  await page.getByLabel('Số tác vụ AI đồng thời').fill('3');
  await page.getByRole('button', { name: 'Lưu cài đặt' }).click();
  await page.waitForTimeout(300);
  assert.equal(studio.store.state.settings.concurrency, 3);
  await page.reload();
  await page.getByRole('heading', { name: 'Bắt đầu bằng một ý tưởng.' }).waitFor();
  await nav('Dựng video');
  assert.equal(await page.locator('.timeline-clip').count(), 4);
  assert.ok(studio.store.state.projects.find((item) => item.name === 'QA · tiếng Việt').timeline.texts.length);
  report.checks.push('Account modal cancellation clears input; tool detection, settings and saved timeline survive reload');
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.screenshot({ path: path.join(output, 'editor-1024.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 390, height: 844 });
  await nav('Tạo bằng AI');
  await page.screenshot({ path: path.join(output, 'create-mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  report.checks.push('No page/console errors and no horizontal overflow at 1024px or 390px');
  report.passed = true;
} catch (error) {
  report.passed = false;
  report.failure = error.stack;
  await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {});
  process.exitCode = 1;
} finally {
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
  await browser.close();
  await studio.close();
}
